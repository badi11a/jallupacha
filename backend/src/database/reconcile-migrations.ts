import 'dotenv/config';
import { DataSource } from 'typeorm';
import { databaseOptions } from '../common/config';
import { applyRuntimeGrants } from './grants';
import { seed } from './seed';

const BASELINE_MIGRATIONS = [
  { timestamp: 1740000000000, name: 'InitialIncrementOne1740000000000' },
  { timestamp: 1740000000001, name: 'MoveSecurityEventIp1740000000001' },
  { timestamp: 1740000000002, name: 'NormalizeSeedIdentityPresentation1740000000002' },
  { timestamp: 1740000000003, name: 'CreateMissingAuditTable1740000000003' },
  { timestamp: 1740000000004, name: 'CreateProcessDrafts1740000000004' },
  { timestamp: 1740000000005, name: 'CreateProcessRisks1740000000005' },
  { timestamp: 1770000000000, name: 'MvpV14Initial1770000000000' }
];

async function reconcile(): Promise<void> {
  const schema = process.env.ORACLE_SCHEMA?.trim().toUpperCase() || 'JALLUPACHA_OWNER';
  const source = new DataSource(databaseOptions(true) as never);
  try {
    await source.initialize();
    console.info('Reconciliando objetos de base de datos en Oracle...');

    const tables: Array<{ TABLE_NAME: string }> = await source.query('SELECT TABLE_NAME FROM USER_TABLES');
    const existingTables = new Set(tables.map((t) => t.TABLE_NAME));

    const seqs: Array<{ SEQUENCE_NAME: string }> = await source.query('SELECT SEQUENCE_NAME FROM USER_SEQUENCES');
    const existingSeqs = new Set(seqs.map((s) => s.SEQUENCE_NAME));

    if (!existingSeqs.has('MACROPROCESS_CODE_SEQ')) {
      await source.query(`CREATE SEQUENCE "${schema}"."MACROPROCESS_CODE_SEQ" START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE`);
      console.info('Creada secuencia MACROPROCESS_CODE_SEQ');
    }

    if (!existingTables.has('RISK_TYPE')) {
      await source.query(`CREATE TABLE "${schema}"."RISK_TYPE" (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NAME VARCHAR2(80 CHAR) NOT NULL UNIQUE,
        IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1))
      )`);
      console.info('Creada tabla RISK_TYPE');
    }

    if (!existingTables.has('RISK_LEVEL')) {
      await source.query(`CREATE TABLE "${schema}"."RISK_LEVEL" (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        NAME VARCHAR2(40 CHAR) NOT NULL UNIQUE,
        IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1))
      )`);
      console.info('Creada tabla RISK_LEVEL');
    }

    if (!existingTables.has('APP_SESSION')) {
      await source.query(`CREATE TABLE "${schema}"."APP_SESSION" (
        SESSION_HASH CHAR(64 CHAR) PRIMARY KEY,
        USER_ID NUMBER NOT NULL REFERENCES "${schema}"."APP_USER"(ID),
        CSRF_HASH CHAR(64 CHAR) NOT NULL,
        LAST_ACTIVITY TIMESTAMP WITH TIME ZONE NOT NULL,
        EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL
      )`);
      await source.query(`CREATE INDEX "${schema}"."IX_APP_SESSION_EXPIRY" ON "${schema}"."APP_SESSION"(EXPIRES_AT)`);
      console.info('Creada tabla APP_SESSION');
    }

    if (!existingTables.has('AUDIT')) {
      await source.query(`CREATE TABLE "${schema}"."AUDIT" (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT (SYSTIMESTAMP AT TIME ZONE 'UTC') NOT NULL,
        ACTOR_USER_ID NUMBER REFERENCES "${schema}"."APP_USER"(ID),
        ACTION VARCHAR2(80 CHAR) NOT NULL,
        ENTITY_TYPE VARCHAR2(40 CHAR) NOT NULL,
        ENTITY_ID VARCHAR2(80 CHAR) NOT NULL,
        BEFORE_VALUE CLOB,
        AFTER_VALUE CLOB
      )`);
      await source.query(`CREATE INDEX "${schema}"."IX_AUDIT_CREATED" ON "${schema}"."AUDIT"(CREATED_AT)`);
      console.info('Creada tabla AUDIT');
    }

    if (!existingTables.has('SECURITY_EVENT')) {
      await source.query(`CREATE TABLE "${schema}"."SECURITY_EVENT" (
        ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT (SYSTIMESTAMP AT TIME ZONE 'UTC') NOT NULL,
        ACTOR_USER_ID NUMBER REFERENCES "${schema}"."APP_USER"(ID),
        EVENT VARCHAR2(40 CHAR) NOT NULL,
        RESULT VARCHAR2(20 CHAR) NOT NULL CHECK (RESULT IN ('SUCCESS', 'REJECTED'))
      )`);
      console.info('Creada tabla SECURITY_EVENT');
    }

    if (!existingTables.has('SECURITY_EVENT_IP')) {
      await source.query(`CREATE TABLE "${schema}"."SECURITY_EVENT_IP" (
        SECURITY_EVENT_ID NUMBER PRIMARY KEY REFERENCES "${schema}"."SECURITY_EVENT"(ID),
        IP_ADDRESS VARCHAR2(64 CHAR) NOT NULL
      )`);
      console.info('Creada tabla SECURITY_EVENT_IP');
    }

    if (!existingTables.has('LOCAL_CREDENTIAL')) {
      await source.query(`CREATE TABLE "${schema}"."LOCAL_CREDENTIAL" (
        USER_ID NUMBER PRIMARY KEY REFERENCES "${schema}"."APP_USER"(ID),
        PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
        FAILED_ATTEMPTS NUMBER(2) DEFAULT 0 NOT NULL,
        LOCKED_UNTIL TIMESTAMP WITH TIME ZONE,
        PASSWORD_UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT (SYSTIMESTAMP AT TIME ZONE 'UTC') NOT NULL
      )`);
      console.info('Creada tabla LOCAL_CREDENTIAL');
    }

    // Reconciliar historial en migrations
    for (const m of BASELINE_MIGRATIONS) {
      const existing = await source.query(
        `SELECT "id" FROM "${schema}"."migrations" WHERE "name" = :1`,
        [m.name]
      );
      if (existing.length === 0) {
        await source.query(
          `INSERT INTO "${schema}"."migrations" ("timestamp", "name") VALUES (:1, :2)`,
          [m.timestamp, m.name]
        );
      }
    }

    // Si LOCAL_CREDENTIAL ya fue creada arriba, registrarla en migrations si no está
    const credMig = await source.query(
      `SELECT "id" FROM "${schema}"."migrations" WHERE "name" = 'CreateLocalCredential1770000000001'`
    );
    if (credMig.length === 0) {
      await source.query(
        `INSERT INTO "${schema}"."migrations" ("timestamp", "name") VALUES (1770000000001, 'CreateLocalCredential1770000000001')`
      );
      console.info('Registrada migración CreateLocalCredential1770000000001');
    }

    // Revocar privilegios excedentes para cumplir estrictamente con grant-runtime.sql
    const runtimeUser = process.env.DATABASE_USER?.trim().toUpperCase() || 'JALLUPACHA_APP';
    try {
      await source.query(`REVOKE DELETE, UPDATE ON "${schema}"."PROCESS_RISK" FROM "${runtimeUser}"`);
      console.info('Revocados privilegios excedentes sobre PROCESS_RISK');
    } catch {
      // ignore
    }

    // Aplicar runtime grants
    console.info('Aplicando grants de runtime para JALLUPACHA_APP...');
    const grantsCount = await applyRuntimeGrants(source);
    console.info(`Grants aplicados: ${grantsCount}`);
  } finally {
    if (source.isInitialized) await source.destroy();
  }

  // Sembrar o actualizar credenciales locales por defecto
  console.info('Sembrando datos y credenciales en Oracle...');
  await seed();
  console.info('Reconciliación y activación de LOCAL_CREDENTIAL completada exitosamente.');
}

reconcile().catch((err: unknown) => {
  console.error('Error durante reconciliación:', err instanceof Error ? err.stack : err);
  process.exit(1);
});
